class CleanRoomCompiler {
  /**
   * Compilação para Componente React TSX de Produção
   * @param {{dna: any, designTokens?: any}} input
   * @returns {string}
   */
  compileToReact(input) {
    const { dna } = input || {};
    if (!dna) throw new Error('CleanRoomCompiler: ComponentDNA não fornecido');

    const componentName = dna.identity?.suggestedArchetype || dna.identity?.semanticName || 'CustomComponent';
    const states = dna.stateMachine?.states || ['idle', 'active'];
    const initialState = dna.stateMachine?.initialState || states[0];
    const stiffness = dna.motionDynamics?.transitions?.[0]?.curveParams?.stiffness ?? 220;
    const damping = dna.motionDynamics?.transitions?.[0]?.curveParams?.damping ?? 18;
    const mass = dna.motionDynamics?.transitions?.[0]?.curveParams?.mass ?? 1;

    if (componentName === 'DraggableWidgetGrid' || dna.geometryConstraints?.layoutMode === 'grid') {
      return `// Code generated by Studio DNA Clean-Room Compiler v1.0.0
// Provenance Hash: ${dna.provenance?.corpusHash || 'N/A'}
// Source Archetype: DraggableWidgetGrid
// Strict Clean-Room: Zero upstream proprietary code reuse

import React, { useState } from 'react';
import { motion, AnimatePresence } from 'framer-motion';

export type GridState = ${states.map((s) => `'${s}'`).join(' | ')};
export type WidgetSpan = '1x1' | '2x1' | '1x2' | '2x2';

export interface WidgetItem {
  id: string;
  title: string;
  widgetType: string;
  span: WidgetSpan;
  locked?: boolean;
  content?: React.ReactNode;
}

export interface DraggableWidgetGridProps {
  widgets: WidgetItem[];
  initialEditMode?: boolean;
  onReorder?: (orderedIds: string[], sourceId: string, targetId: string) => void;
  onResizeSpan?: (widgetId: string, newSpan: WidgetSpan) => void;
  onRemoveWidget?: (widgetId: string) => void;
}

const SPAN_CLASSES: Record<WidgetSpan, string> = {
  '1x1': 'col-span-1 row-span-1',
  '2x1': 'col-span-2 row-span-1',
  '1x2': 'col-span-1 row-span-2',
  '2x2': 'col-span-2 row-span-2',
};

export const DraggableWidgetGrid: React.FC<DraggableWidgetGridProps> = ({
  widgets: initialWidgets,
  initialEditMode = false,
  onReorder,
  onResizeSpan,
  onRemoveWidget,
}) => {
  const [items, setItems] = useState<WidgetItem[]>(initialWidgets);
  const [gridState, setGridState] = useState<GridState>(initialEditMode ? 'edit_mode' : '${initialState}');
  const [draggedId, setDraggedId] = useState<string | null>(null);
  const [hoverTargetId, setHoverTargetId] = useState<string | null>(null);

  const isEditing = gridState !== 'idle_locked';

  const handleSwap = (sourceId: string, targetId: string) => {
    if (sourceId === targetId) return;
    const sourceIdx = items.findIndex((w) => w.id === sourceId);
    const targetIdx = items.findIndex((w) => w.id === targetId);
    if (sourceIdx < 0 || targetIdx < 0) return;
    if (items[sourceIdx].locked || items[targetIdx].locked) return;

    const next = [...items];
    const [moved] = next.splice(sourceIdx, 1);
    next.splice(targetIdx, 0, moved);
    setItems(next);
    setGridState('drop_settling');
    if (onReorder) {
      onReorder(next.map((w) => w.id), sourceId, targetId);
    }
  };

  const cycleSpan = (widget: WidgetItem) => {
    if (!isEditing || widget.locked) return;
    const order: WidgetSpan[] = ['1x1', '2x1', '1x2', '2x2'];
    const nextSpan = order[(order.indexOf(widget.span) + 1) % order.length];
    setItems((prev) => prev.map((w) => (w.id === widget.id ? { ...w, span: nextSpan } : w)));
    if (onResizeSpan) onResizeSpan(widget.id, nextSpan);
  };

  return (
    <section
      role="${dna.accessibilityContract?.ariaRole || 'region'}"
      aria-label="${dna.identity?.semanticName || 'DraggableWidgetGrid'}"
      className="w-full p-6 rounded-2xl bg-[var(--hub-surface-canvas,#09090b)] border border-[var(--hub-border-subtle,#27272a)] text-[var(--hub-text-primary,#fafafa)]"
    >
      <header className="flex items-center justify-between mb-4">
        <div className="flex items-center gap-2">
          <span className="text-sm font-semibold tracking-tight">Workspace Widgets</span>
          <span className="text-xs px-2 py-0.5 rounded-full bg-zinc-800 text-zinc-400">{gridState}</span>
        </div>
        <button
          type="button"
          onClick={() => setGridState(isEditing ? 'idle_locked' : 'edit_mode')}
          className="px-3 py-1.5 text-xs font-medium rounded-lg border border-zinc-700 hover:bg-zinc-800 transition-colors"
        >
          {isEditing ? 'Concluir Edição' : 'Personalizar Grid'}
        </button>
      </header>

      <div className="grid grid-cols-1 md:grid-cols-4 auto-rows-[minmax(180px,auto)] gap-4">
        <AnimatePresence>
          {items.map((widget, idx) => (
            <motion.div
              key={widget.id}
              layout
              draggable={isEditing && !widget.locked}
              onDragStart={() => {
                setDraggedId(widget.id);
                setGridState('dragging_active');
              }}
              onDragOver={(e) => {
                e.preventDefault();
                if (draggedId && draggedId !== widget.id) {
                  setHoverTargetId(widget.id);
                  setGridState('drop_target_hover');
                }
              }}
              onDrop={() => {
                if (draggedId && draggedId !== widget.id) {
                  handleSwap(draggedId, widget.id);
                }
                setDraggedId(null);
                setHoverTargetId(null);
              }}
              onKeyDown={(e) => {
                if (!isEditing || widget.locked) return;
                if ((e.key === 'ArrowRight' || e.key === 'ArrowDown') && idx < items.length - 1) {
                  e.preventDefault();
                  handleSwap(widget.id, items[idx + 1].id);
                } else if ((e.key === 'ArrowLeft' || e.key === 'ArrowUp') && idx > 0) {
                  e.preventDefault();
                  handleSwap(widget.id, items[idx - 1].id);
                } else if (e.key === 'Escape') {
                  setDraggedId(null);
                  setGridState('edit_mode');
                }
              }}
              tabIndex={0}
              aria-grabbed={draggedId === widget.id}
              aria-dropeffect="move"
              transition={{
                type: 'spring',
                stiffness: ${stiffness},
                damping: ${damping},
                mass: ${mass},
              }}
              className={\`\${SPAN_CLASSES[widget.span]} relative flex flex-col justify-between p-4 rounded-xl bg-[var(--hub-surface-card,#18181b)] border \${
                hoverTargetId === widget.id ? 'border-indigo-500 ring-2 ring-indigo-500/30' : 'border-zinc-800'
              } select-none focus:outline-none focus:ring-2 focus:ring-indigo-500\`}
            >
              <div className="flex items-center justify-between gap-2 mb-2">
                <div className="flex items-center gap-2">
                  {isEditing && !widget.locked && (
                    <span aria-label="Drag handle" className="cursor-grab active:cursor-grabbing text-zinc-400">
                      ⋮⋮
                    </span>
                  )}
                  <h3 className="text-sm font-medium">{widget.title}</h3>
                </div>
                {isEditing && !widget.locked && (
                  <div className="flex items-center gap-1">
                    <button
                      type="button"
                      onClick={() => cycleSpan(widget)}
                      className="px-2 py-0.5 text-[11px] rounded bg-zinc-800 hover:bg-zinc-700 text-zinc-300"
                    >
                      {widget.span}
                    </button>
                    {onRemoveWidget && (
                      <button
                        type="button"
                        onClick={() => onRemoveWidget(widget.id)}
                        aria-label={\`Remover \${widget.title}\`}
                        className="px-1.5 py-0.5 text-[11px] rounded bg-red-950/60 hover:bg-red-900/70 text-red-300"
                      >
                        ×
                      </button>
                    )}
                  </div>
                )}
              </div>
              <div className="flex-1 overflow-auto">{widget.content}</div>
            </motion.div>
          ))}
        </AnimatePresence>
      </div>
    </section>
  );
};
`;
    }

    return `// Code generated by Studio DNA Clean-Room Compiler v1.0.0
// Provenance Hash: ${dna.provenance?.corpusHash || 'N/A'}
// Source Archetype: ${componentName}
// Strict Clean-Room: Zero upstream proprietary code reuse

import React, { useState, useEffect, useRef } from 'react';
import { motion, AnimatePresence } from 'framer-motion';

export type ComponentState = ${states.map((s) => `'${s}'`).join(' | ')};

export interface ${componentName}Props {
  onSendMessage?: (content: string) => Promise<void>;
  status?: ComponentState;
  children?: React.ReactNode;
}

export const ${componentName}: React.FC<${componentName}Props> = ({
  onSendMessage,
  status = '${initialState}',
  children
}) => {
  const [internalState, setInternalState] = useState<ComponentState>(status);
  const [inputContent, setInputContent] = useState('');
  const textareaRef = useRef<HTMLTextAreaElement>(null);
  const streamViewportRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (textareaRef.current) {
      textareaRef.current.style.height = 'auto';
      textareaRef.current.style.height = \`\${textareaRef.current.scrollHeight}px\`;
    }
  }, [inputContent]);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!inputContent.trim() || internalState === 'submitting') return;

    setInternalState('submitting');
    try {
      if (onSendMessage) await onSendMessage(inputContent);
      setInputContent('');
      setInternalState('${initialState}');
    } catch {
      setInternalState('interrupted_error');
    }
  };

  return (
    <div
      role="${dna.accessibilityContract?.ariaRole || 'region'}"
      aria-label="${dna.identity?.semanticName || componentName}"
      className="flex flex-col h-full w-full bg-slate-50 dark:bg-slate-950 rounded-2xl overflow-hidden border border-slate-200 dark:border-slate-800"
    >
      <div 
        ref={streamViewportRef}
        className="flex-1 overflow-y-auto p-4 space-y-4"
      >
        <AnimatePresence>
          {children}
        </AnimatePresence>
      </div>

      <motion.form
        onSubmit={handleSubmit}
        className="p-3 bg-white dark:bg-slate-900 border-t border-slate-200 dark:border-slate-800"
        transition={{
          type: 'spring',
          stiffness: ${stiffness},
          damping: ${damping},
          mass: ${mass}
        }}
      >
        <div className="flex items-end gap-2">
          <textarea
            ref={textareaRef}
            rows={1}
            value={inputContent}
            onChange={(e) => {
              setInputContent(e.target.value);
              setInternalState(e.target.value ? 'typing_with_content' : '${initialState}');
            }}
            onKeyDown={(e) => {
              if (e.key === 'Enter' && !e.shiftKey) {
                e.preventDefault();
                handleSubmit(e);
              }
            }}
            placeholder="Digite uma instrução..."
            className="flex-1 max-h-48 resize-none bg-transparent text-sm focus:outline-none placeholder-slate-400"
          />
          <button
            type="submit"
            disabled={!inputContent.trim() || internalState === 'submitting'}
            className="px-4 py-2 bg-indigo-600 hover:bg-indigo-700 disabled:opacity-40 text-white text-sm font-medium rounded-xl transition-colors"
          >
            Enviar
          </button>
        </div>
      </motion.form>
    </div>
  );
};
`;
  }

  /**
   * Compilação para Especificação Declarativa de Generative UI do Hub Agent
   * @param {{dna: any, designTokens?: any}} input
   * @returns {object}
   */
  compileToHubGenUISpec(input) {
    const { dna } = input;
    if (!dna) throw new Error('CleanRoomCompiler: ComponentDNA não fornecido');

    const componentName = dna.identity?.suggestedArchetype || 'CustomComponent';
    const subcomponents = dna.anatomy?.subcomponents || [];

    if (componentName === 'DraggableWidgetGrid' || dna.geometryConstraints?.layoutMode === 'grid') {
      return {
        schemaVersion: 'hub.genui.v1',
        archetypeRef: 'DraggableWidgetGrid',
        layout: {
          type: 'bento-draggable-grid',
          props: {
            columns: 4,
            gapPx: 16,
            minRowHeightPx: 180,
            allowReorder: true,
            allowSpanResize: true,
            supportedSpans: ['1x1', '2x1', '1x2', '2x2'],
            springPhysics: {
              stiffness: dna.motionDynamics?.transitions?.[0]?.curveParams?.stiffness ?? 300,
              damping: dna.motionDynamics?.transitions?.[0]?.curveParams?.damping ?? 28,
              mass: dna.motionDynamics?.transitions?.[0]?.curveParams?.mass ?? 1
            }
          }
        },
        slots: subcomponents.map((sub) => ({
          role: sub.role,
          optional: Boolean(sub.optional),
          permittedWidgets: [
            'ApprovalGate',
            'ExecutionTimeline',
            'ConversationalShell',
            'ToolCallDisclosure',
            'ReasoningSummary',
            'ArtifactPreview',
            'metric-card',
            'markdown-stream'
          ]
        })),
        runtimeBinding: {
          layoutStateTopic: 'agent.genui.layout_state',
          reorderActionTopic: 'agent.genui.layout_updated',
          resizeSpanActionTopic: 'agent.genui.widget_resized',
          removeWidgetActionTopic: 'agent.genui.widget_removed'
        }
      };
    }

    return {
      schemaVersion: 'hub.genui.v1',
      archetypeRef: componentName,
      layout: {
        type: 'shell-stack',
        props: {
          density: dna.geometryConstraints?.density || 'normal',
          dockedBottom: true
        }
      },
      slots: subcomponents.map((sub) => ({
        role: sub.role,
        optional: Boolean(sub.optional),
        permittedWidgets: ['markdown-stream', 'tool-call-card', 'diff-view', 'action-buttons']
      })),
      runtimeBinding: {
        streamStateTopic: 'agent.run.stream',
        submitAction: 'agent.user.prompt',
        approvalTopic: 'agent.tool.request_approval'
      }
    };
  }
}

