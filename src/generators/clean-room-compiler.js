/**
 * Clean-Room Component Compiler
 * Sintetiza implementações originais em React TSX e Hub GenUI a partir de ComponentDNA / Archetypes.
 * Regra Inegociável: ZERO acesso de leitura ao diretório copias/.
 */

class CleanRoomCompiler {
  /**
   * Compilação para Componente React TSX de Produção
   * @param {{dna: any, designTokens?: any}} input
   * @returns {string}
   */
  compileToReact(input) {
    const { dna } = input;
    if (!dna) throw new Error('CleanRoomCompiler: ComponentDNA não fornecido');

    const componentName = dna.identity?.suggestedArchetype || 'CustomComponent';
    const states = dna.stateMachine?.states || ['idle', 'active'];
    const initialState = dna.stateMachine?.initialState || states[0];
    const stiffness = dna.motionDynamics?.transitions?.[0]?.curveParams?.stiffness ?? 220;
    const damping = dna.motionDynamics?.transitions?.[0]?.curveParams?.damping ?? 18;
    const mass = dna.motionDynamics?.transitions?.[0]?.curveParams?.mass ?? 1;

    return `// Code generated by Studio DNA Clean-Room Compiler v1.0.0
// Provenance Hash: ${dna.provenance?.corpusHash || 'N/A'}
// Source Archetype: ${componentName}
// Strict Clean-Room: Zero upstream proprietary code reuse

import React, { useState, useEffect, useRef } from 'react';
import { motion, AnimatePresence } from 'framer-motion';

export type ComponentState = ${states.map((s) => `'${s}'`).join(' | ')};

export interface ${componentName}Props {
  onSendMessage?: (content: string) => Promise<void>;
  status?: ComponentState;
  children?: React.ReactNode;
}

export const ${componentName}: React.FC<${componentName}Props> = ({
  onSendMessage,
  status = '${initialState}',
  children
}) => {
  const [internalState, setInternalState] = useState<ComponentState>(status);
  const [inputContent, setInputContent] = useState('');
  const textareaRef = useRef<HTMLTextAreaElement>(null);
  const streamViewportRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (textareaRef.current) {
      textareaRef.current.style.height = 'auto';
      textareaRef.current.style.height = \`\${textareaRef.current.scrollHeight}px\`;
    }
  }, [inputContent]);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!inputContent.trim() || internalState === 'submitting') return;

    setInternalState('submitting');
    try {
      if (onSendMessage) await onSendMessage(inputContent);
      setInputContent('');
      setInternalState('${initialState}');
    } catch {
      setInternalState('interrupted_error');
    }
  };

  return (
    <div
      role="${dna.accessibilityContract?.ariaRole || 'region'}"
      aria-label="${dna.identity?.semanticName || componentName}"
      className="flex flex-col h-full w-full bg-slate-50 dark:bg-slate-950 rounded-2xl overflow-hidden border border-slate-200 dark:border-slate-800"
    >
      <div 
        ref={streamViewportRef}
        className="flex-1 overflow-y-auto p-4 space-y-4"
      >
        <AnimatePresence>
          {children}
        </AnimatePresence>
      </div>

      <motion.form
        onSubmit={handleSubmit}
        className="p-3 bg-white dark:bg-slate-900 border-t border-slate-200 dark:border-slate-800"
        transition={{
          type: 'spring',
          stiffness: ${stiffness},
          damping: ${damping},
          mass: ${mass}
        }}
      >
        <div className="flex items-end gap-2">
          <textarea
            ref={textareaRef}
            rows={1}
            value={inputContent}
            onChange={(e) => {
              setInputContent(e.target.value);
              setInternalState(e.target.value ? 'typing_with_content' : '${initialState}');
            }}
            onKeyDown={(e) => {
              if (e.key === 'Enter' && !e.shiftKey) {
                e.preventDefault();
                handleSubmit(e);
              }
            }}
            placeholder="Digite uma instrução..."
            className="flex-1 max-h-48 resize-none bg-transparent text-sm focus:outline-none placeholder-slate-400"
          />
          <button
            type="submit"
            disabled={!inputContent.trim() || internalState === 'submitting'}
            className="px-4 py-2 bg-indigo-600 hover:bg-indigo-700 disabled:opacity-40 text-white text-sm font-medium rounded-xl transition-colors"
          >
            Enviar
          </button>
        </div>
      </motion.form>
    </div>
  );
};
`;
  }

  /**
   * Compilação para Especificação Declarativa de Generative UI do Hub Agent
   * @param {{dna: any, designTokens?: any}} input
   * @returns {object}
   */
  compileToHubGenUISpec(input) {
    const { dna } = input;
    if (!dna) throw new Error('CleanRoomCompiler: ComponentDNA não fornecido');

    const componentName = dna.identity?.suggestedArchetype || 'CustomComponent';
    const subcomponents = dna.anatomy?.subcomponents || [];

    return {
      schemaVersion: 'hub.genui.v1',
      archetypeRef: componentName,
      layout: {
        type: 'shell-stack',
        props: {
          density: dna.geometryConstraints?.density || 'normal',
          dockedBottom: true
        }
      },
      slots: subcomponents.map((sub) => ({
        role: sub.role,
        optional: Boolean(sub.optional),
        permittedWidgets: ['markdown-stream', 'tool-call-card', 'diff-view', 'action-buttons']
      })),
      runtimeBinding: {
        streamStateTopic: 'agent.run.stream',
        submitAction: 'agent.user.prompt',
        approvalTopic: 'agent.tool.request_approval'
      }
    };
  }
}

module.exports = { CleanRoomCompiler };
